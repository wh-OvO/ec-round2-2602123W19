static float fabs_f(float x)
{
  return (x < 0.0f) ? -x : x;
}

/* ------------------------------------------------------------------------- */
/* 限幅：把 *v 夹进 [-lim, +lim]                                              */
/*                                                                            */
/* TODO(3) 参数为什么是 `float *v` 而不是 `float v`？                           */
/*         返回值 hit 是给谁用的？                                             */
/*                                                                            */
/* 答：                                                                        */
/* ------------------------------------------------------------------------- */
static uint8_t clamp_f(float *v, float lim)
{
  uint8_t hit = 0u;

  if (*v > lim)
  {
    *v  = lim;
    hit = 1u;
  }
  else if (*v < -lim)
  {
    *v  = -lim;
    hit = 1u;
  }

  return hit;
}

