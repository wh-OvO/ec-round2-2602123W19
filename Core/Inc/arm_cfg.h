/* ---- 几何角 → 舵机命令角的映射 ------------------------------------------
 *
 *      命令角 = ARM_KIN_Jn_OFF_DEG + ARM_KIN_Jn_SIGN × 几何角
 *
 *   几何角的定义（和关节装在哪无关，只看连杆朝向）：
 *
 *                 J2 = 大臂的绝对仰角     J3 = 肘的弯曲量
 *     竖直向下          −90°                  —
 *     水平前伸            0°                  0°（两连杆共线）
 *     竖直向上          +90°                  —
 *     折成直角            —                  90°
 *     折到底              —                 180°
 *
 *   ⚠️ OFF / SIGN 现在的 0 / +1 只是**占位**，标定完必须改。
 *      猜错的后果不是报错，是"能跑但跑到别的地方去" —— 比报错难查得多。
 *
 *   怎么定（摆两个姿态就能量出来，不用猜）：
 *      ① 大臂摆水平前伸，读它此时的命令角 a      ⇒ OFF_J2 = a
 *      ② 大臂抬到竖直向上，命令角 b              ⇒ SIGN_J2 = (b − a) / 90
 *         （b > a 取 +1.0，b < a 取 −1.0）
 *      ③ 两连杆伸直，读 J3 命令角 c              ⇒ OFF_J3 = c
 *      ④ 折 90°，读 J3 命令角 e                  ⇒ SIGN_J3 = (e − c) / 90
 *      ⑤ 校验：四个数填回去，用 0x25 给一个已知点，量实际末端位置；
 *         和期望差 > 10mm 就说明某一步错了
 */
