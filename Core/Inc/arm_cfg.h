#define ARM_KIN_J2_OFF_DEG   0.0f     /* ← 待标定 */
#endif
#ifndef ARM_KIN_J2_SIGN
#define ARM_KIN_J2_SIGN      1.0f     /* ← 待标定：只能是 +1.0 或 −1.0 */
#endif
#ifndef ARM_KIN_J3_OFF_DEG
#define ARM_KIN_J3_OFF_DEG   0.0f     /* ← 待标定 */
#endif
#ifndef ARM_KIN_J3_SIGN
#define ARM_KIN_J3_SIGN      1.0f     /* ← 待标定：只能是 +1.0 或 −1.0 */
#endif

