/* ==========================================================================
 * 六、插补器参数（T2）
 *
 *     插补器把"从 A 跳到 B"拆成每 5ms 一小步，四轴按同一进度 s 走，
 *     所以四个关节**同时出发、同时到达**。
 * ========================================================================== */

/* ★★★ 重点：插补节拍为什么是 5ms，以及为什么要和上报周期拆开 ★★★
 *
 * 任务书 T2 原文：「插补周期不低于 200Hz」→ 5ms。原来的 20ms 只有 50Hz，差 4 倍。
 *
 * 但 0x10 状态帧要求的是 20~50Hz，两者**不能共用一个节拍了**：
 *     ARM_INTERP_TICK_MS  5ms  → interp_tick() + arm_joint_tick()，不出帧
 *     APP_REPORT_MS      20ms  → send_status()，不推进插补
 *
 * 200Hz 的插补**不会**让舵机动得更细 —— 舵机 PPM 是 50Hz，CCR 实际上每 20ms
 * 才真正生效一次，这是模拟舵机的物理限制。那 200Hz 有什么用？
 * 任务书后半句：「相邻两拍的角度增量连续，不允许出现阶跃」——它判的是
 * **插补器每拍算出来的角度增量**。5ms 一拍算出来的增量是连续的，
 * 20ms 一拍算出来的是大台阶，起步和停止那两下就是阶跃。 */
#define ARM_INTERP_TICK_MS       5u

/* 梯形曲线的加减速段各占总时长的比例（0.2 = 各占 20%）。
 *
 *   时间轴：|←加速 20%→|←—— 匀速 60% ——→|←减速 20%→|
 *   速度图：             ╱‾‾‾‾‾‾‾‾‾‾╲
 *                      ╱            ╲
 *
 * 调大 → 起停更柔，但匀速段变短、峰值速度更高（见 proto_app.c 的推导）；
 * 调小 → 更接近匀速，但加速度更猛，机械冲击变大。
 * 舵机 + 3D 打印臂这种轻负载，0.2 是比较稳的选择。 */
#define ARM_TRAP_ACC_RATIO       0.2f
#define ARM_HOMING_MS            800u     /* 回零（0x21=2）走多久，比手动快一点但要稳 */
#define ARM_MOVING_STILL_DEG     1.0f     /* 底座误差小于这个就算"已到位"（给状态位 bit3 用） */

