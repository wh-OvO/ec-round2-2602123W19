/**
  * @brief 一个 PID 控制器实例（参数 + 状态）
  *
  * TODO(1) 为什么"参数"和"状态"要分成两段？各自谁会改？
  *
  * 答：参数是固定的，状态是运行时变化的，分成两段改起来方便
  *
  * TODO(2) 结构体里没有一个指针、没有一次 malloc —— 为什么裸机上必须这样？
  *
  * 答：不知道
  */
typedef struct
{
  /* ===== 参数段：调用方填 ============================================== */
  float kp;        /* 比例增益     单位：输出 / 误差            */
  float ki;        /* 积分增益     单位：输出 / (误差 × 秒)      */
  float kd;        /* 微分增益     单位：输出 / (误差 / 秒)      */
  float dt_s;      /* 采样周期(秒) 200Hz → 0.005f。<= 0 时禁用 I/D */
  float out_max;   /* 输出限幅 ±   （与输出同单位）。<= 0 表示不限幅 */
  float i_max;     /* 积分项上限 ± （与输出同单位）。<= 0 表示不限   */
  float deadband;  /* 死区        （与误差同单位）。<= 0 表示无死区  */
  float d_tau_s;   /* D 项一阶低通时间常数(秒)。<= 0 表示不滤波     */
  float d_max;     /* 微分合理性上限（测量值单位/秒）。本拍 |d(测量)/dt|
                      超过它 ⇒ 认定这一拍测量无效：微分置 0、滤波状态清零，
                      但 prev_meas 照常更新，所以只丢这一拍。<= 0 表示不检查。
                      ★ 存在的理由：测量值若是"会绕回"的角度（±180），
                        跨接缝那一拍会跳 360°，微分会算出物理上不可能的数。*/

  /* ===== 状态段：arm_pid_reset() 清零，调用方不要手改 ================== */
  float   integ;
  float   prev_meas;
  float   d_state;
  uint8_t started;
  uint8_t sat;/*#saturation（饱和）；置1说明pid理论值超上限被截断，说明输出饱和，一旦检测就冻结积分，实现抗积分饱和#*/
} arm_pid_t;

/**
  * @brief  清空控制器状态（积分器 / 微分历史 / 限幅标志）
  * @param  p 控制器实例；传 0 直接返回
  *
  * TODO(3) 为什么它**不清** kp/ki/kd/dt_s 这些参数？
  *         什么时候该调它？（本工程里能在 arm_joint.c 找到 4 处调用）
  *
  * 答： 这些参数是根据实际情况确定的，清零状态是为了重新开始控制，参数不需要清零，只有在工程结构发生变化或者需要重新调节参数时才需要修改这些参数
  */
void arm_pid_reset(arm_pid_t *p);

/**
  * @brief  走一拍 PID
  * @param  p    控制器实例（参数必须已填好）
  * @param  err  本拍误差 = 目标 − 测量（调用方负责绕 ±180 等归一化）
  * @param  meas 本拍测量值。只在 kd != 0 时参与运算
  * @param  ff   本拍前馈，直接加到输出上（与输出同单位）。没有就传 0
  * @retval 本拍输出（与输出同单位），已过死区 / 限幅
  *
  * TODO(4) err 和 meas 其实满足 `err = 目标 − meas`，那为什么两个都要传？
  *         只传 err 行不行，会丢什么信息？
  *
  * 答：
  *
  * TODO(5) 为什么 err 的 ±180° 归一化不放在这一层做？
  *
  * 答： 不知道
  *
  * TODO(6) "当 ki == 0 且 kd == 0 时输出必须与旧纯 P 代码逐位相同" ——
  *         为什么这是一条硬指标，而不是"能对上大概就行"？
  *
  * 答：不然会漂移，具体为什么我不知道，我猜是积分爆炸
  */
float arm_pid_step(arm_pid_t *p, float err, float meas, float ff);

